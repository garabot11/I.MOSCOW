"""Write configs/val_sweep.yaml: distance and object-count sweep in the organisers' insertion style.

    env -u PYTHONPATH python tools/make_sweep_config.py      (from solution/synth)

A) one object at a fixed distance (5-300 m) on a standing train, four classes;
B) approach from 300 m on a moving train;
C) 1-16 objects per frame, standing and moving (fake_a objects do not occlude each other, so 16 is a load case
   rather than a physical scene); the 8-object scene also in the in_place and physical styles.
"""
import os

import yaml

CLS = {"person_standing": {"cls": "person_standing", "lat": 0.0},
       "box": {"cls": "box", "lat": 0.2, "size": [0.5, 0.5, 0.5]},
       "cube": {"cls": "cube", "lat": 0.6, "size": [0.3, 0.3, 0.3], "bottom_m": 1.0},     # theirs: 0.9-1.5 m above bed
       "wall": {"cls": "wall", "lat": 0.0, "size": [2.9, 4.0, 0.02]}}                     # theirs: 2.9 x 4 m
DIST = [5, 10, 20, 40, 60, 80, 100, 125, 150, 175, 200, 230, 270, 300]
POOL = [("person_standing", {"lat": -0.4}), ("box", {"lat": 0.3, "size": [0.5, 0.5, 0.5]}),
        ("cube", {"lat": 0.6, "size": [0.3, 0.3, 0.3], "bottom_m": 1.0}),
        ("plate", {"lat": 0.0, "size": [1.3, 0.6, 0.15], "bottom_m": 0.35}), ("person_crouching", {"lat": 0.2}),
        ("side_box", {"lat": 2.6, "size": [2.0, 2.4, 2.0]}), ("wall", {"lat": 0.0, "size": [2.0, 2.0, 0.02]}),
        ("person_standing", {"lat": 2.0})]
COUNT_D = [25, 110, 60, 140, 40, 85, 15, 125, 50, 95, 30, 150, 70, 20, 115, 45]
STAND = "squareT_platform_squareT_switch"     # station section, verified range 175 m, standing


def objs(n, key):
    return [dict(POOL[k % len(POOL)][1], cls=POOL[k % len(POOL)][0], **{key: float(COUNT_D[k])}) for k in range(n)]


def scenes():
    out = []
    for c, p in CLS.items():
        for d in DIST:
            out.append((f"dist_{c}_{d}", {"style": "fake_a", "base": STAND, "frames": [323, 362], "standing": True,
                                          "objects": [dict(p, d0=float(d))]}))
    for c, p in CLS.items():      # new_data 4750-4899 travels 210 m: 300 -> 90 m
        out.append((f"appr_{c}_300to90", {"style": "fake_a", "base": "new_data", "frames": [4750, 4899],
                                          "objects": [dict(p, d_end=90.0)]}))
    for c, p in CLS.items():      # new_data 1250-1399 travels 110 m: 300 -> 190 m
        out.append((f"appr_{c}_300to190", {"style": "fake_a", "base": "new_data", "frames": [1250, 1399],
                                           "objects": [dict(p, d_end=190.0)]}))
    for n in (1, 2, 4, 8, 16):
        out.append((f"count_stand_{n}", {"style": "fake_a", "base": STAND, "frames": [525, 584], "standing": True,
                                         "objects": objs(n, "d0")}))
    for n in (1, 4, 8, 16):       # new_data 2000-2149 travels 62 m
        out.append((f"count_move_{n}", {"style": "fake_a", "base": "new_data", "frames": [2000, 2149],
                                        "objects": objs(n, "d_end")}))
    for style in ("in_place", "physical"):
        out.append((f"count_stand_8_{style}", {"style": style, "base": STAND, "frames": [525, 584], "standing": True,
                                               "objects": objs(8, "d0")}))
    return out


def main():
    sc = scenes()
    cfg = {"set": "val_sweep", "source": "fake_style", "sensor": "hesai128", "storage": "mcap", "seed": 20261020,
           "frame_id": "hesai_lidar", "topic": "/lidar_points", "scenes": {"list": [s for _t, s in sc]}}
    hdr = ("# Generated by tools/make_sweep_config.py - distance (5-300 m) and object-count (1-16) sweep in the organisers'\n"
           "# insertion style.  Scene index -> tag:\n" + "".join(f"#   {i:3d} {t}\n" for i, (t, _s) in enumerate(sc)))
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "configs", "val_sweep.yaml")
    with open(path, "w") as fh:
        fh.write(hdr + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None, width=140))
    print(path, len(sc), "scenes", sum(s["frames"][1] - s["frames"][0] + 1 for _t, s in sc), "frames")


if __name__ == "__main__":
    main()
